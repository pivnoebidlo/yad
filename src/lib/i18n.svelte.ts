const dicts: Record<Locale, Dict> = { en: en as Dict, ru };
export type MsgKey = keyof Dict;
type Vars = Record<string, string | number>;

const fill = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);

/** Translate a message; `{name}` placeholders are filled from `vars`. */
export function t(key: MsgKey, vars?: Vars): string {
  const v = dicts[effectiveLocale()][key] ?? dicts.en[key];
  return fill(Array.isArray(v) ? v[v.length - 1] : v, vars);
}

/** Plural form for `n` (English: one/other; Russian: one/few/many). */
export function tn(key: MsgKey, n: number, vars?: Vars): string {
  const locale = effectiveLocale();
  const v = dicts[locale][key] ?? dicts.en[key];
  if (!Array.isArray(v)) return fill(v, { n, ...vars });
  let i: number;
  if (locale === "ru") {
    const m10 = n % 10, m100 = n % 100;
    i = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
  } else i = n === 1 ? 0 : 1;
  return fill(v[Math.min(i, v.length - 1)], { n, ...vars });
}

/** Keys that exist in English but are missing in another dictionary (used by a test). */
export const missingKeys = (locale: Locale) => (Object.keys(en) as MsgKey[]).filter((k) => !(k in dicts[locale]));
